def camel(text: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", text)
    words = [part for part in parts if part]
    return words[0].lower() + "".join(word[:1].upper() + word[1:] for word in words[1:])


def function_name(method: str, path: str) -> str:
    if (method, path) in NAMES:
        return NAMES[(method, path)]
    body = path.removeprefix("/api/v1").strip("/")
    chunks: list[str] = []
    for part in body.split("/"):
        if part.startswith("{") and part.endswith("}"):
            chunks.append("by")
            chunks.append(part[1:-1])
        else:
            chunks.append(part)
    return camel(method + " " + " ".join(chunks))


def path_params(path: str) -> list[str]:
    return re.findall(r"\{([^{}]+)\}", path)


def main() -> None:
    spec = app.openapi()
    spec["info"]["description"] = (
        "Halo Front Office HTTP API. Generated from the FastAPI application. "
        "Fixture mode does not call a commercial model."
    )
    openapi_path = ROOT / "contracts" / "openapi.json"
    openapi_path.write_text(json.dumps(spec, indent=2) + "\n")

    lines = [
        "// Generated by scripts/generate_api_client.py. Do not edit.",
        'import { api } from "./client";',
        'import type { CompanyCard, CompanyDetail, Evidence, Me, Overview, Packet } from "./types";',
        "",
        "export type RosterPerson = { id: string; display_name: string; email: string; role: string };",
        "export type JsonObject = Record<string, unknown>;",
        "",
        "function withQuery(path: string, query: Record<string, string | number | undefined>) {",
        "  const params = new URLSearchParams();",
        "  for (const [key, value] of Object.entries(query)) {",
        '    if (value !== undefined && value !== "") params.set(key, String(value));',
        "  }",
        "  const text = params.toString();",
        '  return text ? `${path}?${text}` : path;',
        "}",
        "",
    ]
    for path, methods in spec["paths"].items():
        for method, operation in methods.items():
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            name = function_name(method, path)
            params = path_params(path)
            query_names = [
                item["name"]
                for item in operation.get("parameters", [])
                if item.get("in") == "query"
            ]
            args: list[str] = []
            for param in params:
                args.append(f"{camel(param)}: string")
            if query_names:
                fields = "; ".join(f"{item}?: string | number" for item in query_names)
                args.append(f"query: {{ {fields} }} = {{}}")
            if method != "get":
                args.append("body: JsonObject = {}")
            response = RESPONSE_TYPES.get((method, path), "JsonObject")
            template = path
            for param in params:
                template = template.replace("{" + param + "}", "${" + camel(param) + "}")
            call_path = f"`{template}`" if "${" in template else f'"{template}"'
            if query_names:
                call_path = f"withQuery({call_path}, query)"
            if method == "get":
                invocation = f"api<{response}>({call_path})"
            else:
                invocation = (
                    f"api<{response}>({call_path}, "
                    f'{{ method: "{method.upper()}", body: JSON.stringify(body) }})'
                )
            lines.append(f"export function {name}({', '.join(args)}) {{")
            lines.append(f"  return {invocation};")
            lines.append("}")
            lines.append("")
    target = ROOT / "apps" / "web" / "src" / "api" / "generated.ts"
    target.write_text("\n".join(lines))
    print(f"wrote {openapi_path.relative_to(ROOT)} and {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
